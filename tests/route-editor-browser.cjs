const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require('playwright');
const base = process.env.WALKY_BASE_URL || 'http://127.0.0.1:4173';
const fixture = fs.readFileSync(path.join(__dirname, 'fixtures/firebase-browser.js'), 'utf8');
const photograph = fs.readFileSync(path.join(__dirname, '../zurag/emoSandal.jpg'));
const output = process.env.WALKY_SCREENSHOTS || '/tmp/walky-route-editor-screenshots';
fs.mkdirSync(output, { recursive: true });

(async () => {
  const browser = await chromium.launch({ headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  await context.route('https://www.gstatic.com/firebasejs/**', route => route.fulfill({ contentType: 'application/javascript', body: route.request().url().includes('firebase-app-compat') ? fixture : '' }));
  await context.route('https://fonts.googleapis.com/**', route => route.fulfill({ contentType: 'text/css', body: '' }));
  await context.route('https://unpkg.com/**', route => route.fulfill({ contentType: route.request().url().includes('.css') ? 'text/css' : 'application/javascript', body: '' }));
  await context.route('https://walky-test-images.example/**', route => route.fulfill({ contentType: 'image/jpeg', body: photograph }));
  const errors = [];
  const admin = await context.newPage();
  admin.on('pageerror', error => errors.push(error.message));
  const settled = () => admin.waitForFunction(() => !document.querySelector('#add-content').disabled);
  const file = { name: 'hike.jpg', mimeType: 'image/jpeg', buffer: photograph };
  try {
    await admin.goto(`${base}/admin.html`);
    await admin.evaluate(() => { __walkyTest.seed({ 'admins/admin': { enabled: true } }); __walkyTest.setUser('admin'); });
    await settled();
    await admin.locator('#import-routes').click(); await settled();
    await admin.locator('[data-edit="bogd-khan-yagaan-sandal"]').click();
    await admin.locator('[name="preparationTitle"]').fill('Алхалтдаа бэлдэх нь');
    await admin.locator('[name="preparation"]').fill('Ундны ус\nБорооны цув\n<img src=x onerror=alert(1)>');
    await admin.locator('[name="audienceTitle"]').fill('Энэ жимийг сонгох хүмүүс');
    await admin.locator('[name="audience"]').fill('Найзуудтайгаа алхахад\nГэр бүлээрээ салхилахад');
    await admin.locator('#route-image-file').setInputFiles({ name: 'unsafe.svg', mimeType: 'image/svg+xml', buffer: Buffer.from('<svg></svg>') });
    await admin.locator('#form-error').waitFor({ state: 'visible' });
    assert.match(await admin.locator('#form-error').textContent(), /JPG/);
    await admin.locator('#route-image-file').setInputFiles(file);
    await admin.waitForFunction(() => document.querySelector('#image-upload-status').textContent.includes('hike.jpg'));
    assert.equal(await admin.evaluate(() => __walkyTest.getUploads().length), 0);
    await admin.locator('#route-image-file').scrollIntoViewIfNeeded();
    await admin.screenshot({ path: path.join(output, 'image-preview-desktop.png'), fullPage: true });
    await admin.evaluate(() => __walkyTest.failUploads({ code: 'storage/unauthorized' }));
    await admin.locator('#save-content').click();
    await admin.locator('#form-error').waitFor({ state: 'visible' });
    assert.equal(await admin.locator('#editor-dialog').isVisible(), true);
    assert.equal(await admin.evaluate(() => __walkyTest.getContent()['routes/bogd-khan-yagaan-sandal'].image), 'zurag/emoSandal.jpg');
    await admin.evaluate(() => __walkyTest.failUploads(null));
    await admin.locator('#save-content').click(); await settled();
    assert.equal(await admin.evaluate(() => __walkyTest.getUploads().length), 1);
    const saved = await admin.evaluate(() => __walkyTest.getContent()['routes/bogd-khan-yagaan-sandal']);
    assert.match(saved.image, /^https:\/\/walky-test-images.example\/route-images\/admin\/.+\.jpg$/);
    assert.deepEqual(saved.preparation, ['Ундны ус', 'Борооны цув', '<img src=x onerror=alert(1)>']);

    const detail = await context.newPage();
    detail.on('pageerror', error => errors.push(error.message));
    await detail.goto(`${base}/route-detail.html?id=bogd-khan-yagaan-sandal`);
    await detail.waitForFunction(() => document.querySelector('#preparation-title').textContent === 'Алхалтдаа бэлдэх нь');
    assert.equal(await detail.locator('#route-preparation span').count(), 3);
    assert.equal(await detail.locator('#route-preparation img').count(), 0);
    assert.equal(await detail.locator('#audience-title').textContent(), 'Энэ жимийг сонгох хүмүүс');
    assert.equal(await detail.locator('#route-audience li').count(), 2);
    assert.equal(await detail.locator('#gallery-image').getAttribute('src'), saved.image);
    await detail.evaluate(() => __walkyTest.setUser(null));
    await detail.locator('#detail-plan-route').click();
    assert.equal(await detail.locator('#detail-plan-route').getAttribute('aria-pressed'), 'true');
    assert.equal(await detail.evaluate(() => WalkyHikes.getState().items['bogd-khan-yagaan-sandal'].status), 'planned');
    await detail.reload();
    await detail.waitForFunction(() => document.querySelector('#detail-plan-route').getAttribute('aria-pressed') === 'true');
    await detail.locator('.detail-hikes-link').click();
    await detail.locator('#tab-planned').click();
    assert.equal(await detail.locator('#planned-hikes').textContent(), '1');
    assert.equal(await detail.locator('#hikes-grid .route-card').count(), 1);
    await detail.goto(`${base}/route-detail.html?id=bogd-khan-yagaan-sandal`);
    await detail.waitForFunction(() => document.querySelector('#preparation-title').textContent === 'Алхалтдаа бэлдэх нь');
    await detail.locator('#detail-plan-route').click();
    assert.equal(await detail.evaluate(() => WalkyHikes.getState().items['bogd-khan-yagaan-sandal'].status), 'saved');
    await detail.evaluate(() => WalkyHikes.setStatus('bogd-khan-yagaan-sandal', 'completed'));
    assert.equal(await detail.locator('#detail-plan-route').isDisabled(), true);
    await detail.evaluate(() => WalkyHikes.setStatus('bogd-khan-yagaan-sandal', 'planned'));
    await detail.evaluate(() => scrollTo(0, 0));
    await detail.screenshot({ path: path.join(output, 'route-details-desktop.png'), fullPage: true });
    for (const width of [320, 390, 768]) {
      await detail.setViewportSize({ width, height: 844 });
      assert.equal(await detail.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
      await detail.locator('#detail-plan-route').scrollIntoViewIfNeeded();
      await detail.screenshot({ path: path.join(output, `route-actions-${width}.png`) });
    }
    await admin.locator('[data-edit="bogd-khan-yagaan-sandal"]').click();
    await admin.locator('[name="preparation"]').fill('');
    await admin.locator('[name="audience"]').fill('');
    await admin.locator('#save-content').click(); await settled();
    await detail.reload();
    await detail.waitForFunction(() => document.querySelector('#preparation-section').hidden);
    assert.equal(await detail.locator('#audience-section').isVisible(), false);
    assert.deepEqual(errors, []);
    console.log('Route editor browser checks passed: custom sections, image preview/upload/retry, safe text, planned hikes, persistence, completed status and responsive layouts.');
    console.log(`Screenshots: ${output}`);
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
